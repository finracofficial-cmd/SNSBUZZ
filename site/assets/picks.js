export const affiliateOn = () => !!SITE.affiliate?.amazonTag;
const amazonUrl = (kw) => `https://www.amazon.co.jp/s?${new URLSearchParams({ k: kw, tag: SITE.affiliate.amazonTag })}`;

export function picksCard(index) {
  if (!affiliateOn() || !PICKS[index]) return '';
  return `<section class="card picks"><h2>このタイプにおすすめ <span class="pr">PR</span></h2>
    <ul class="pick-list">${PICKS[index]
      .map(([label, kw]) => `<li><a href="${esc(amazonUrl(kw))}" target="_blank" rel="sponsored noopener" data-aff="${index}">${esc(label)}<span>Amazonで見る →</span></a></li>`)
      .join('')}</ul>
    <p class="hint">Amazonのアソシエイトとして、${esc(SITE.name)}は適格販売により収入を得ています。</p>
  </section>`;
}
